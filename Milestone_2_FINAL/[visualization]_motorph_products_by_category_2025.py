def plot_revenue_by_category(summary):
    """Horizontal bar chart: Q3 revenue per category (PHP millions), annotated with the number of models."""
    data = summary.sort_values("Q3 Revenue (PHP)", ascending=True)
    top_cat  = data["Category"].iloc[-1]
    best_cat = summary.sort_values("Revenue per Model (PHP)", ascending=False)["Category"].iloc[0]
    colors = ["#1F4E79" if c == top_cat else "#E07B39" if c == best_cat else "#8FB3D9" for c in data["Category"]]
    millions = data["Q3 Revenue (PHP)"] / 1e6

    fig, ax = plt.subplots(figsize=(11, 8))
    bars = ax.barh(data["Category"], millions, color=colors, edgecolor="white")
    for bar, m, share, n in zip(bars, millions, data["Share of Revenue (%)"], data["Number of Products"]):
        ax.text(bar.get_width() + 8, bar.get_y() + bar.get_height() / 2,
                f"PHP {m:,.1f}M ({share:.1f}%) | {n} model{'s' if n > 1 else ''}", va="center", fontsize=9.5)
    ax.set_title("Q3 2025 Revenue by Product Category", fontsize=15, fontweight="bold", pad=14)
    ax.set_xlabel("Q3 Revenue (PHP millions)", fontsize=12)
    ax.set_ylabel("Product Category", fontsize=12)
    ax.set_xlim(0, millions.max() * 1.38)
    ax.grid(axis="x", linestyle="--", alpha=0.4); ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    fig.text(0.99, 0.01, f"Dark blue = highest revenue ({top_cat}); orange = highest revenue per model ({best_cat})",
             ha="right", va="bottom", fontsize=9, style="italic", color="dimgray")
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    return fig

def plot_share_comparison(summary):
    """Side-by-side bars: share of products vs share of revenue for each category."""
    import numpy as np
    data = summary.sort_values("Share of Revenue (%)", ascending=True)
    y, h = np.arange(len(data)), 0.4
    fig, ax = plt.subplots(figsize=(11, 8))
    ax.barh(y + h / 2, data["Share of Products (%)"], h, label="Share of products (%)", color="#8FB3D9")
    ax.barh(y - h / 2, data["Share of Revenue (%)"],  h, label="Share of Q3 revenue (%)", color="#1F4E79")
    ax.set_yticks(y); ax.set_yticklabels(data["Category"])
    ax.set_title("Share of Products vs Share of Revenue by Category", fontsize=15, fontweight="bold", pad=14)
    ax.set_xlabel("Share of total (%)", fontsize=12)
    ax.set_ylabel("Product Category", fontsize=12)
    ax.legend(loc="lower right", frameon=False)
    ax.grid(axis="x", linestyle="--", alpha=0.4); ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    fig.tight_layout()
    return fig

fig_rev   = plot_revenue_by_category(category_summary)
